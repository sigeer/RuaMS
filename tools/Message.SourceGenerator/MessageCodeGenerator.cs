using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Message.SourceGenerator
{
    /// <summary>
    /// 读取 i18n/{Category}/{Language}.json，为每个类别生成强类型常量类。
    /// 目录名即类名，JSON 的键并集即常量集合，常量值等于键名（与 nameof 语义一致）。
    /// </summary>
    [Generator]
    public class MessageCodeGenerator : IIncrementalGenerator
    {
        public const string Namespace = "Application.Resources.Messages";

        private static readonly DiagnosticDescriptor InvalidKey = new DiagnosticDescriptor(
            id: "MSG001",
            title: "消息键不是合法的 C# 标识符",
            messageFormat: "类别 {0} 中的键 \"{1}\" 不是合法的 C# 标识符，已跳过常量生成",
            category: "Message",
            defaultSeverity: DiagnosticSeverity.Info,
            isEnabledByDefault: true);

        private static readonly DiagnosticDescriptor ReservedKey = new DiagnosticDescriptor(
            id: "MSG002",
            title: "消息键与生成成员冲突",
            messageFormat: "类别 {0} 中的键 \"{1}\" 与保留成员同名，请重命名该键",
            category: "Message",
            defaultSeverity: DiagnosticSeverity.Error,
            isEnabledByDefault: true);

        private static readonly HashSet<string> _reserved = new HashSet<string>(StringComparer.Ordinal)
        {
            "Get",
            "Format",
            "ResourceManager",
            "ResourceCulture"
        };

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var files = context.AdditionalTextsProvider
                .Where(static f => f.Path.EndsWith(".json", StringComparison.OrdinalIgnoreCase))
                .Select(static (f, ct) =>
                {
                    var category = Path.GetFileName(Path.GetDirectoryName(f.Path));
                    var text = f.GetText(ct);
                    return new MessageFile(category, f.Path, text?.ToString() ?? string.Empty);
                })
                .Where(static f => !string.IsNullOrEmpty(f.Category));

            var collected = files.Collect();

            context.RegisterSourceOutput(collected, static (spc, items) => Execute(spc, items));
        }

        private static void Execute(SourceProductionContext context, ImmutableArray<MessageFile> items)
        {
            var groups = items
                .GroupBy(static f => f.Category!, StringComparer.Ordinal)
                .OrderBy(static g => g.Key, StringComparer.Ordinal);

            foreach (var group in groups)
            {
                var className = group.Key;
                if (!IsValidIdentifier(className))
                {
                    context.ReportDiagnostic(Diagnostic.Create(InvalidKey, Location.None, className, className));
                    continue;
                }

                var keys = new SortedSet<string>(StringComparer.Ordinal);
                foreach (var file in group.OrderBy(static f => f.Path, StringComparer.Ordinal))
                    foreach (var key in ReadKeys(file.Content))
                        keys.Add(key);

                var source = BuildSource(className, keys, ReadComments(group), context);
                if (source == null)
                    return;

                context.AddSource($"{className}.g.cs", SourceText.From(source, Encoding.UTF8));
            }
        }

        /// <summary>
        /// 每个键的注释取 zh-CN 文案；没有 zh-CN 时退回第一条能解析出该键的语言。
        /// 换行压成字面量 \n，避免注释里出现真实换行（XML 文档注释里也难以阅读）。
        /// </summary>
        private static Dictionary<string, string> ReadComments(IGrouping<string, MessageFile> group)
        {
            var files = group.OrderBy(static f => f.Path, StringComparer.Ordinal).ToList();
            var preferred = files.FindIndex(static f =>
                string.Equals(Path.GetFileNameWithoutExtension(f.Path), "zh-CN", StringComparison.OrdinalIgnoreCase));

            var result = new Dictionary<string, string>(StringComparer.Ordinal);

            var sources = preferred >= 0 ? new List<MessageFile> { files[preferred] } : files;
            foreach (var file in sources)
            {
                foreach (var entry in ReadEntries(file.Content))
                    result[entry.Key] = entry.Value;
            }

            return result;
        }

        private static string? BuildSource(string className, SortedSet<string> keys, Dictionary<string, string> comments, SourceProductionContext context)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("#nullable disable");
            sb.AppendLine();
            sb.AppendLine("using System.Globalization;");
            sb.AppendLine();
            sb.Append("namespace ").AppendLine(Namespace);
            sb.AppendLine("{");
            sb.Append("    public static partial class ").AppendLine(className);
            sb.AppendLine("    {");

            foreach (var key in keys)
            {
                if (!IsValidIdentifier(key))
                {
                    context.ReportDiagnostic(Diagnostic.Create(InvalidKey, Location.None, className, key));
                    continue;
                }

                if (_reserved.Contains(key))
                {
                    context.ReportDiagnostic(Diagnostic.Create(ReservedKey, Location.None, className, key));
                    return null;
                }

                if (comments.TryGetValue(key, out var comment) && comment.Length > 0)
                {
                    sb.Append("        /// <summary>").Append(EscapeXml(comment)).AppendLine("</summary>");
                }

                sb.Append("        public const string ").Append(key)
                  .Append(" = \"").Append(key).AppendLine("\";");
            }
            sb.AppendLine();
            sb.Append("        public static string? Get(string key, CultureInfo? culture = null) =>")
              .Append(" MessageStore.Get(").Append(Quote(className)).AppendLine(", key, culture);");
            sb.AppendLine();
            sb.Append("        public static string Format(string key, CultureInfo? culture, params object[] args) =>")
              .Append(" MessageStore.Format(").Append(Quote(className)).AppendLine(", key, culture, args);");
            sb.AppendLine();
            sb.Append("        public static string? GetDefault(string key) =>")
              .Append(" MessageStore.GetDefault(").Append(Quote(className)).AppendLine(", key);");
            sb.AppendLine();
            sb.Append("        public static string FormatDefault(string key, params object[] args) =>")
              .Append(" MessageStore.FormatDefault(").Append(Quote(className)).AppendLine(", key, args);");

            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }

        private static string Quote(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

        /// <summary>
        /// XML 文档注释里不能出现裸的 &lt; &amp;，换行也会把注释拆散，统一转义/压平。
        /// </summary>
        private static string EscapeXml(string value)
        {
            var sb = new StringBuilder(value.Length);
            for (var i = 0; i < value.Length; i++)
            {
                var c = value[i];
                switch (c)
                {
                    case '&': sb.Append("&amp;"); break;
                    case '<': sb.Append("&lt;"); break;
                    case '>': sb.Append("&gt;"); break;
                    case '\r':
                        if (i + 1 < value.Length && value[i + 1] == '\n')
                            i++;
                        sb.Append("\\n");
                        break;
                    case '\n':
                        sb.Append("\\n");
                        break;
                    default: sb.Append(c); break;
                }
            }

            return sb.ToString();
        }

        /// <summary>
        /// 从扁平 JSON 对象中取出第一层的键，不需要完整反序列化。
        /// </summary>
        private static IEnumerable<string> ReadKeys(string json)
        {
            foreach (var entry in ReadEntries(json))
                yield return entry.Key;
        }

        /// <summary>
        /// 取出第一层的键值对（生成注释用）。值必须是字符串。
        /// </summary>
        private static IEnumerable<KeyValuePair<string, string>> ReadEntries(string json)
        {
            var depth = 0;
            var i = 0;
            while (i < json.Length)
            {
                var c = json[i];
                if (c == '{' || c == '[')
                {
                    depth++;
                    i++;
                    continue;
                }

                if (c == '}' || c == ']')
                {
                    depth--;
                    i++;
                    continue;
                }

                if (c != '"')
                {
                    i++;
                    continue;
                }

                var key = ReadJsonString(json, i);
                if (key == null)
                    yield break;

                i = key.Value.Next;

                // 第一层且后面紧跟冒号的字符串才是键
                if (depth != 1 || !TrySkipTo(json, ref i, ':'))
                    continue;

                i++;
                if (!TrySkipTo(json, ref i, '"'))
                    continue;

                var value = ReadJsonString(json, i);
                if (value == null)
                    yield break;

                i = value.Value.Next;
                yield return new KeyValuePair<string, string>(key.Value.Text, value.Value.Text);
            }
        }

        private static bool TrySkipTo(string json, ref int index, char expected)
        {
            while (index < json.Length && char.IsWhiteSpace(json[index]))
                index++;

            return index < json.Length && json[index] == expected;
        }

        /// <summary>
        /// 读取从 <paramref name="start"/>（必须是引号）开始的 JSON 字符串。
        /// </summary>
        private static JsonString? ReadJsonString(string json, int start)
        {
            if (start >= json.Length || json[start] != '"')
                return null;

            var i = start + 1;
            var escaped = false;
            while (i < json.Length)
            {
                var ch = json[i];
                if (escaped)
                {
                    escaped = false;
                }
                else if (ch == '\\')
                {
                    escaped = true;
                }
                else if (ch == '"')
                {
                    break;
                }
                i++;
            }

            if (i >= json.Length)
                return null;

            return new JsonString(Unescape(json.Substring(start + 1, i - start - 1)), i + 1);
        }

        private readonly struct JsonString
        {
            public JsonString(string text, int next)
            {
                Text = text;
                Next = next;
            }

            public string Text { get; }
            public int Next { get; }
        }

        private static string Unescape(string value)
        {
            if (value.IndexOf('\\') < 0)
                return value;

            var sb = new StringBuilder(value.Length);
            for (var i = 0; i < value.Length; i++)
            {
                var c = value[i];
                if (c != '\\' || i + 1 >= value.Length)
                {
                    sb.Append(c);
                    continue;
                }

                var next = value[++i];
                switch (next)
                {
                    case '"': sb.Append('"'); break;
                    case '\\': sb.Append('\\'); break;
                    case '/': sb.Append('/'); break;
                    case 'b': sb.Append('\b'); break;
                    case 'f': sb.Append('\f'); break;
                    case 'n': sb.Append('\n'); break;
                    case 'r': sb.Append('\r'); break;
                    case 't': sb.Append('\t'); break;
                    case 'u':
                        if (i + 4 < value.Length && int.TryParse(value.Substring(i + 1, 4), System.Globalization.NumberStyles.HexNumber, null, out var code))
                        {
                            sb.Append((char)code);
                            i += 4;
                        }
                        break;
                    default: sb.Append(next); break;
                }
            }

            return sb.ToString();
        }

        private static bool IsValidIdentifier(string value)
        {
            if (string.IsNullOrEmpty(value))
                return false;

            if (!char.IsLetter(value[0]) && value[0] != '_')
                return false;

            for (var i = 1; i < value.Length; i++)
            {
                if (!char.IsLetterOrDigit(value[i]) && value[i] != '_')
                    return false;
            }

            switch (value)
            {
                case "abstract": case "as": case "base": case "bool": case "break":
                case "byte": case "case": case "catch": case "char": case "checked":
                case "class": case "const": case "continue": case "decimal": case "default":
                case "delegate": case "do": case "double": case "else": case "enum":
                case "event": case "explicit": case "extern": case "false": case "finally":
                case "fixed": case "float": case "for": case "foreach": case "goto":
                case "if": case "implicit": case "in": case "int": case "interface":
                case "internal": case "is": case "lock": case "long": case "namespace":
                case "new": case "null": case "object": case "operator": case "out":
                case "override": case "params": case "private": case "protected": case "public":
                case "readonly": case "ref": case "return": case "sbyte": case "sealed":
                case "short": case "sizeof": case "stackalloc": case "static": case "string":
                case "struct": case "switch": case "this": case "throw": case "true":
                case "try": case "typeof": case "uint": case "ulong": case "unchecked":
                case "unsafe": case "ushort": case "using": case "virtual": case "void":
                case "volatile": case "while":
                    return false;
                default:
                    return true;
            }
        }

        private readonly struct MessageFile
        {
            public MessageFile(string? category, string path, string content)
            {
                Category = category;
                Path = path;
                Content = content;
            }

            public string? Category { get; }
            public string Path { get; }
            public string Content { get; }
        }
    }
}
